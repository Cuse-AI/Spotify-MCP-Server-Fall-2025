import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import type { PlaylistResponse, TapestrySong } from "@shared/schema";
import { ThumbsUp, ThumbsDown, Quote } from "lucide-react";
import { apiRequest } from "@/lib/queryClient";
import { useToast } from "@/hooks/use-toast";
import { useState } from "react";
import { CosmicBackground } from "./cosmic-background";
import { SoulGem } from "./soul-gem";
import { JourneyHeader } from "./journey-header";

interface PlaylistResultsProps {
  data: PlaylistResponse;
  onStartOver: () => void;
}

export function PlaylistResults({ data, onStartOver }: PlaylistResultsProps) {
  const { toast } = useToast();
  const [validatedSongs, setValidatedSongs] = useState<Set<string>>(new Set());
  const [downvotedSongs, setDownvotedSongs] = useState<Set<string>>(new Set());
  const [creatingPlaylist, setCreatingPlaylist] = useState(false);

  const handleCreateSpotifyPlaylist = async () => {
    setCreatingPlaylist(true);
    try {
      const trackUris = data.songs.map(song => {
        const id = song.track_id.replace('spotify:track:', '');
        return `spotify:track:${id}`;
      });
      
      const playlistName = `Tapestry: ${data.journey.vibe || 'Emotional Journey'}`;
      const playlistDescription = `From "${data.journey.now}" to "${data.journey.going}" • Generated by Tapestry`;
      
      const response = await apiRequest("POST", "/api/create-spotify-playlist", {
        playlistName,
        playlistDescription,
        trackUris,
      });
      
      const result = await response.json();
      
      toast({
        title: "Playlist Created! 🎉",
        description: "Opening in Spotify...",
        duration: 3000,
      });
      
      window.open(result.playlistUrl, '_blank');
    } catch (error: any) {
      toast({
        variant: "destructive",
        title: "Failed to Create Playlist",
        description: error.message || "Could not connect to Spotify",
        duration: 5000,
      });
    } finally {
      setCreatingPlaylist(false);
    }
  };

  const handleValidateSong = async (song: TapestrySong) => {
    try {
      const response = await apiRequest("POST", "/api/validate-song", {
        song: {
          track_id: song.track_id,
          artist: song.artist,
          title: song.title,
          sub_vibe: song.sub_vibe,
          meta_vibe: song.meta_vibe,
          confidence: song.confidence,
          manifold_x: song.manifold_x,
          manifold_y: song.manifold_y,
          emotional_composition: song.emotional_composition,
          extrapolated: song.extrapolated,
        },
        user_journey: data.journey,
      });

      const result = await response.json();
      setValidatedSongs((prev) => new Set(prev).add(song.track_id));
      
      toast({
        title: result.boosted ? "⬆️ Confidence boosted!" : "✨ Added to Tapestry!",
        description: result.boosted 
          ? `"${song.title}" validation count increased`
          : `"${song.title}" is now part of the manifold`,
        duration: 1500,
      });
    } catch (error) {
      toast({
        variant: "destructive",
        title: "Error",
        description: "Failed to add song to Tapestry",
        duration: 1500,
      });
    }
  };

  const handleDownvoteSong = async (song: TapestrySong) => {
    try {
      await apiRequest("POST", "/api/downvote-song", {
        song: {
          track_id: song.track_id,
          artist: song.artist,
          title: song.title,
          sub_vibe: song.sub_vibe,
          meta_vibe: song.meta_vibe,
          confidence: song.confidence,
          manifold_x: song.manifold_x,
          manifold_y: song.manifold_y,
          emotional_composition: song.emotional_composition,
          extrapolated: song.extrapolated,
        },
        user_journey: data.journey,
      });

      setDownvotedSongs((prev) => new Set(prev).add(song.track_id));
      
      toast({
        title: "Feedback recorded",
        description: `"${song.title}" flagged for review`,
        duration: 1500,
      });
    } catch (error) {
      toast({
        variant: "destructive",
        title: "Error",
        description: "Failed to record feedback",
        duration: 1500,
      });
    }
  };

  if (!data || !data.songs || data.songs.length === 0) {
    return (
      <div className="min-h-screen px-6 py-12 md:px-8 flex items-center justify-center">
        <Card className="p-8 max-w-md text-center">
          <h2 className="text-xl font-medium mb-4">No Playlist Generated</h2>
          <p className="text-muted-foreground mb-6">
            We couldn't generate your playlist. Please try again.
          </p>
          <Button onClick={onStartOver} data-testid="button-start-over">
            Try Again
          </Button>
        </Card>
      </div>
    );
  }

  return (
    <>
      <CosmicBackground />
      <div className="min-h-screen px-6 py-12 md:px-8 relative z-10">
        <div className="max-w-3xl mx-auto">
          
          {/* Soul Gem - Centered hero */}
          <div className="flex justify-center mb-6">
            <SoulGem songs={data.songs} size={260} />
          </div>

          {/* Header - Title + AI description with elegant typography */}
          <JourneyHeader 
            playlistTitle={data.playlistTitle || "Your Emotional Journey"}
            explanation={data.explanation}
          />

          {/* Playlist Card with 3D depth */}
          <Card 
            className="mb-8 overflow-hidden border border-white/[0.08] bg-gradient-to-b from-white/[0.04] to-white/[0.01] shadow-[0_0_30px_rgba(168,85,247,0.12),inset_0_1px_0_rgba(255,255,255,0.06)]" 
            data-testid="card-playlist"
          >
            <div className="divide-y divide-white/[0.06]">
              {data.songs.map((song, index) => {
                const isValidated = validatedSongs.has(song.track_id);
                const isDownvoted = downvotedSongs.has(song.track_id);
                const isExtrapolated = song.extrapolated === true;
                const spotifyUrl = `https://open.spotify.com/track/${song.track_id.replace('spotify:track:', '')}`;
                
                return (
                  <div
                    key={`${song.track_id}-${index}`}
                    className="flex items-center gap-4 p-4 hover:bg-white/[0.02] transition-all relative group"
                    data-testid={`song-item-${index}`}
                  >
                    {/* Track number */}
                    <span className="text-sm text-white/30 w-6 text-right font-mono">
                      {index + 1}
                    </span>
                    
                    {/* Song info */}
                    <div className="flex-1 min-w-0 pr-20">
                      <h3 className="font-medium truncate text-white/90" data-testid={`text-song-title-${index}`}>
                        <a 
                          href={spotifyUrl}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="hover:text-primary transition-colors"
                        >
                          {song.title}
                        </a>
                      </h3>
                      <p className="text-sm text-white/50 truncate" data-testid={`text-song-artist-${index}`}>
                        {song.artist}
                      </p>
                      <p className="text-xs text-white/30 mt-1">
                        {song.sub_vibe}
                        {isExtrapolated && <span className="ml-2 text-primary">✨ AI discovery</span>}
                      </p>
                    </div>
                    
                    {/* Feedback buttons - ONLY show for extrapolated songs */}
                    {isExtrapolated && (
                      <div className="absolute bottom-3 right-3 flex gap-2">
                        <button
                          onClick={() => handleValidateSong(song)}
                          disabled={isValidated || isDownvoted}
                          className={`p-1.5 rounded-md transition-all border ${
                            isValidated
                              ? "text-green-500 border-green-500 opacity-100"
                              : isDownvoted
                              ? "text-white/20 border-transparent opacity-30 cursor-not-allowed"
                              : "text-white/30 border-transparent opacity-40 hover:opacity-100 hover:border-green-500 hover:text-green-500"
                          }`}
                          data-testid={`button-validate-song-${index}`}
                          title={isValidated ? "Added to Tapestry!" : isDownvoted ? "Already downvoted" : "Great match - add to Tapestry"}
                        >
                          <ThumbsUp className="w-3.5 h-3.5" fill={isValidated ? "currentColor" : "none"} />
                        </button>
                        
                        <button
                          onClick={() => handleDownvoteSong(song)}
                          disabled={isDownvoted || isValidated}
                          className={`p-1.5 rounded-md transition-all border ${
                            isDownvoted
                              ? "text-red-500 border-red-500 opacity-100"
                              : isValidated
                              ? "text-white/20 border-transparent opacity-30 cursor-not-allowed"
                              : "text-white/30 border-transparent opacity-40 hover:opacity-100 hover:border-red-500 hover:text-red-500"
                          }`}
                          data-testid={`button-downvote-song-${index}`}
                          title={isDownvoted ? "Flagged for review" : isValidated ? "Already validated" : "Poor match"}
                        >
                          <ThumbsDown className="w-3.5 h-3.5" fill={isDownvoted ? "currentColor" : "none"} />
                        </button>
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
          </Card>

          {/* Actions */}
          <div className="flex flex-col sm:flex-row gap-4 justify-center">
            <Button
              size="lg"
              className="px-8"
              data-testid="button-create-spotify-playlist"
              onClick={handleCreateSpotifyPlaylist}
              disabled={creatingPlaylist}
            >
              {creatingPlaylist ? "Creating..." : "Create Playlist on Spotify"}
            </Button>
            <Button
              size="lg"
              variant="outline"
              className="px-8"
              onClick={onStartOver}
              data-testid="button-start-over"
            >
              Start Over
            </Button>
          </div>

          {/* Song Stories - The Human Context */}
          {data.songs.some((s) => s.reddit_context || s.ananki_reasoning) && (
            <details className="mt-12">
              <summary className="text-sm text-white/40 cursor-pointer hover:text-white/60 transition-colors text-center">
                Why these songs? See the stories behind each pick
              </summary>
              <div className="mt-6 space-y-4">
                {data.songs.map((song, index) => {
                  const isExtrapolated = song.extrapolated === true;
                  const humanQuote = !isExtrapolated ? song.reddit_context : undefined;
                  const aiReasoning = song.ananki_reasoning;
                  
                  const sourceLabel = song.source_url?.includes('youtube') 
                    ? 'YouTube comment' 
                    : song.source_url?.includes('reddit') 
                      ? 'Reddit' 
                      : 'the community';
                  
                  if (!humanQuote && !aiReasoning) return null;
                  
                  return (
                    <Card 
                      key={`detail-${song.track_id}-${index}`} 
                      className="p-5 bg-white/[0.02] border-white/[0.06]"
                    >
                      <h4 className="font-medium text-sm text-white/70 mb-3">
                        {song.title} — {song.artist}
                        {isExtrapolated && <span className="ml-2 text-xs text-white/40">(AI discovery)</span>}
                      </h4>
                      
                      {humanQuote && (
                        <div className="mb-4">
                          <div className="flex gap-3">
                            <Quote className="w-4 h-4 text-white/30 flex-shrink-0 mt-0.5" />
                            <blockquote className="text-white/60 italic text-sm leading-relaxed">
                              "{humanQuote}"
                            </blockquote>
                          </div>
                          <p className="text-xs text-white/30 mt-2 ml-7">
                            — from {sourceLabel}
                          </p>
                        </div>
                      )}
                      
                      {aiReasoning && (
                        <div className={humanQuote ? "border-t border-white/[0.06] pt-3 mt-3" : ""}>
                          <p className="text-xs text-white/50 leading-relaxed">
                            <span className="font-medium text-white/60">Why it fits: </span>
                            {aiReasoning}
                          </p>
                        </div>
                      )}
                    </Card>
                  );
                })}
              </div>
            </details>
          )}
        </div>
      </div>
    </>
  );
}
